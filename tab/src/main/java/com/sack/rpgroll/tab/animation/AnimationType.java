package com.sack.rpgroll.tab.animation;

/** FRAME: ciclo de textos completos. SCROLL: desplaza una ventana sobre un texto largo. BLINK: alterna texto/vacío. PROGRESS: barra de progreso generada a partir de un placeholder 0-100. */
public enum AnimationType {
    FRAME,
    SCROLL,
    BLINK,
    PROGRESS
}
